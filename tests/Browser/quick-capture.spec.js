const { test, expect } = require('@playwright/test');
const fs = require('node:fs');
const crypto = require('node:crypto');

test('Vorlage schnell erfassen und manuelle Rückfahrt mit änderbaren Vorgaben', async ({ page }) => {
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    const credentialFile = process.env.E2E_CREDENTIAL_FILE;
    if (!credentialFile) throw new Error('Isolierte Testzugangsdaten über E2E_CREDENTIAL_FILE erforderlich.');
    const username = 'demo.meyer';
    const line = fs.readFileSync(credentialFile, 'utf8').split('\n').find(line => line.startsWith(username + ': '));
    const password = line.slice(username.length + 2).trim();
    await page.goto('/anmelden');
    await page.locator('#username').fill(username);
    await page.locator('#password').fill(password);
    await page.getByRole('button', { name: /Anmelden/ }).click();
    await page.waitForURL(url => url.pathname !== '/anmelden');
    if (new URL(page.url()).pathname === '/passwort') {
        const replacement = crypto.randomBytes(24).toString('base64url');
        await page.locator('#current_password').fill(password);
        await page.locator('#password').fill(replacement);
        await page.locator('#password_confirmation').fill(replacement);
        await page.getByRole('button', { name: 'Passwort speichern', exact: true }).click();
        await page.waitForURL(url => url.pathname === '/');
        fs.writeFileSync(credentialFile, fs.readFileSync(credentialFile, 'utf8').replace(line, username + ': ' + replacement), { mode: 0o600 });
    }

    await page.goto('/vorlagen/create');
    const templateName = 'Schule Browser ' + crypto.randomBytes(4).toString('hex');
    await page.getByLabel('Name der Vorlage').fill(templateName);
    await page.getByLabel('Start', { exact: true }).fill('Rathaus');
    await page.locator('#destination').fill('Schule');
    await page.getByLabel('Fahrtzweck').fill('IT-Betreuung');
    await page.getByLabel('Standardfahrzeug').selectOption({ index: 1 });
    await page.getByLabel('Entfernung Hinfahrt (km)').fill('2.2');
    await page.getByLabel('Rückfahrt einschließen').check();
    await page.getByLabel('Als Favorit auf der Übersicht anzeigen').check();
    await page.getByRole('button', { name: 'Vorlage speichern', exact: true }).click();
    await page.goto('/');
    await page.getByRole('link').filter({ hasText: templateName }).click();
    await expect(page.getByRole('heading', { level: 1 })).toHaveText('Schnellerfassung: ' + templateName);
    await expect(page.locator('#journey-distance')).toHaveText('4,40 km');
    await expect(page.getByLabel('Start der Rückfahrt')).toHaveValue('Schule');
    await expect(page.getByLabel('Ziel der Rückfahrt')).toHaveValue('Rathaus');
    await page.getByLabel('Datum', { exact: true }).fill('2026-10-15');
    await expect(page.getByLabel('Rückfahrdatum')).toHaveValue('2026-10-15');
    await page.getByLabel('Entfernung Hinfahrt (km)').fill('2.6');
    await expect(page.getByLabel('Entfernung Rückfahrt (km)')).toHaveValue('2.6');
    await expect(page.locator('#journey-distance')).toHaveText('5,20 km');
    await page.getByLabel('Entfernung Rückfahrt (km)').fill('3.1');
    await page.getByLabel('Entfernung Hinfahrt (km)').fill('2.8');
    await expect(page.getByLabel('Entfernung Rückfahrt (km)')).toHaveValue('3.1');
    await expect(page.locator('#journey-distance')).toHaveText('5,90 km');
    await page.getByLabel('Rückfahrt einschließen').uncheck();
    await expect(page.locator('#return-fields')).toBeHidden();
    await expect(page.locator('#journey-distance')).toHaveText('2,80 km');
    await page.getByLabel('Rückfahrt einschließen').check();
    await page.getByLabel('Fahrtbeginn', { exact: true }).fill('08:00');
    await page.getByLabel('Fahrtende', { exact: true }).fill('08:10');
    await page.getByLabel('Rückfahrt Beginn').fill('12:00');
    await page.getByLabel('Rückfahrt Ende').fill('12:10');
    await page.getByLabel('Rückfahrt Ende').fill('11:00');
    await page.getByRole('button', { name: 'Entwürfe gemeinsam speichern' }).click();
    await expect(page.getByRole('alert')).toContainText('Rückfahrt');
    await expect(page.getByLabel('Entfernung Rückfahrt (km)')).toHaveValue('3.1');
    await expect(page.locator('#journey-distance')).toHaveText('5,90 km');
    await page.getByLabel('Rückfahrt Ende').fill('12:10');
    await page.getByRole('button', { name: 'Entwürfe gemeinsam speichern' }).click();
    await expect(page.getByRole('status').first()).toContainText('Hin- und Rückfahrt');
    await expect(page.getByLabel('Kilometerstand Beginn', { exact: true })).toHaveValue('');
    await expect(page.getByLabel('Geschäftlich (km)', { exact: true })).toHaveValue('2.80');
    await page.getByRole('link', { name: /Zugehörige Rückfahrt/ }).click();
    await expect(page.getByLabel('Geschäftlich (km)', { exact: true })).toHaveValue('3.10');

    await page.goto('/fahrten/create');
    await page.getByLabel('Start', { exact: true }).fill('Rathaus');
    await page.getByLabel('Ziel', { exact: true }).fill('Bauhof');
    await page.getByLabel('Reiseroute', { exact: true }).fill('Rathaus → Bauhof');
    await page.getByLabel('Geschäftlich (km)', { exact: true }).fill('2.2');
    await expect(page.locator('#distance-output')).toHaveText('2,20 km');
    await page.getByLabel('Rückfahrt hinzufügen').check();
    await expect(page.getByLabel('Start der Rückfahrt')).toHaveValue('Bauhof');
    await expect(page.getByLabel('Ziel der Rückfahrt')).toHaveValue('Rathaus');
    await expect(page.getByLabel('Geschäftlich Rückfahrt (km)')).toHaveValue('2.2');
    await page.getByLabel('Geschäftlich Rückfahrt (km)').fill('4.1');
    await page.getByLabel('Geschäftlich (km)', { exact: true }).fill('3.1');
    await expect(page.getByLabel('Geschäftlich Rückfahrt (km)')).toHaveValue('4.1');
    await page.setViewportSize({ width: 390, height: 844 });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy();
    expect(errors).toEqual([]);
});
